-- Schema for the Student Management app.
-- Written in portable SQL so the same migration runs on H2 (default) and PostgreSQL (postgres profile).

CREATE TABLE students (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name    VARCHAR(50)              NOT NULL,
    last_name     VARCHAR(50)              NOT NULL,
    email         VARCHAR(100)             NOT NULL,
    date_of_birth DATE                     NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_students_email UNIQUE (email)
);

CREATE TABLE courses (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(10)              NOT NULL,
    title       VARCHAR(100)             NOT NULL,
    description VARCHAR(500),
    credits     INTEGER                  NOT NULL,
    capacity    INTEGER                  NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_courses_code UNIQUE (code),
    CONSTRAINT ck_courses_credits CHECK (credits BETWEEN 1 AND 6),
    CONSTRAINT ck_courses_capacity CHECK (capacity BETWEEN 1 AND 500)
);

CREATE TABLE enrollments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id  BIGINT NOT NULL,
    course_id   BIGINT NOT NULL,
    enrolled_on DATE   NOT NULL,
    CONSTRAINT uk_enrollments_student_course UNIQUE (student_id, course_id),
    CONSTRAINT fk_enrollments_student FOREIGN KEY (student_id) REFERENCES students (id) ON DELETE CASCADE,
    CONSTRAINT fk_enrollments_course FOREIGN KEY (course_id) REFERENCES courses (id) ON DELETE CASCADE
);

-- (student_id, course_id) is already indexed by the unique constraint; add the reverse lookup.
CREATE INDEX idx_enrollments_course_id ON enrollments (course_id);
